"""Build the MLOps handoff, RAGOps plan and cost-aware operating plan.

Reads mlops/*.yaml, the assumptions register and projections, ADR-003, the
contract layer and the security matrix; checks they agree; writes:

  docs/mlops_churn_handoff.md
  docs/ragops_plan.md
  docs/cost_operating_plan.md

Exits non-zero if a coupling check fails. Pending sign-offs on the cost
estimate (COST-G1) and the RAG evaluation method (RAG-G1) are reported, not failed.

Usage:
    python scripts/build_mlops.py
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

import pandas as pd
import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from aurora_contracts.conformance import MICRO_BATCH_LANDING_MINUTES  # noqa: E402
from aurora_contracts.loader import load as load_contracts  # noqa: E402
from aurora_mlops import cost  # noqa: E402
from aurora_mlops.gates import signoff_status  # noqa: E402
from build_assumptions import SCENARIOS, load_assumptions  # noqa: E402
from build_security_matrix import load_matrix, regimes_in_scope, resolve_retention  # noqa: E402

MLOPS = ROOT / "mlops"
DOCS = ROOT / "docs"
ADR_003 = next((DOCS / "adr").glob("ADR-003-*.md"))


def _yaml(name: str) -> dict:
    with (MLOPS / name).open(encoding="utf-8") as fh:
        return yaml.safe_load(fh)


def md(df: pd.DataFrame, index: bool = False) -> str:
    return df.to_markdown(index=index)


def usd(x: float) -> str:
    return f"${x:,.0f}" if abs(x) >= 10 else f"${x:,.2f}"


def signoff_table(rows: list[dict]) -> str:
    return md(pd.DataFrame(rows).rename(columns=str.title))


# ----------------------------------------------------------------- checks
def coupling_checks(a, cfg, rag, handoff, claims, security, contracts) -> list[tuple[str, bool, str]]:
    checks = []
    title = ADR_003.read_text(encoding="utf-8").splitlines()[0]
    checks.append(("Ingestion pattern matches ADR-003", cfg["ingestion"]["pattern"].lower() in title.lower(), title))
    checks.append((
        "Landing cadence matches contract layer",
        cfg["ingestion"]["landing_minutes"] == MICRO_BATCH_LANDING_MINUTES,
        f"{cfg['ingestion']['landing_minutes']} min vs contracts {MICRO_BATCH_LANDING_MINUTES} min",
    ))
    max_tokens = contracts.datasets["rag.transcript_chunks"].column("token_count").max_value
    checks.append(("Chunk cap matches A-TRN-04 and contract", max_tokens == a["A-TRN-04"]["base"] == 512,
                   f"contract {max_tokens:g}, A-TRN-04 {a['A-TRN-04']['base']}"))
    thr = rag["evaluation"]["release_thresholds"]
    checks.append(("Cost-per-conversation threshold equals A-BUD-03",
                   thr["cost_per_conversation_usd"]["max"] == a["A-BUD-03"]["base"],
                   f"{thr['cost_per_conversation_usd']['max']} vs {a['A-BUD-03']['base']}"))
    c01 = claims.set_index("claim_id").loc["C-AI-01", "pass_threshold"]
    recall = float(re.search(r"Recall@5 >= ([0-9.]+)", c01).group(1))
    checks.append(("recall@5 threshold equals C-AI-01", thr["recall@5"]["min"] == recall, f"{thr['recall@5']['min']} vs {recall}"))
    for name, t in thr.items():
        if "claim" in t:
            checks.append((f"{name} claim exists", t["claim"] in set(claims["claim_id"]), t["claim"]))
    gates = {g["id"] for g in security["review_gates"]}
    for g in rag["meta"]["preconditions"]:
        if g.startswith("SEC-"):
            checks.append((f"Precondition {g} exists in security matrix", g in gates, g))
    checks.append(("Model priced in price book", all(a["A-LLM-05"][s] in cfg["price_book"]["models"] for s in SCENARIOS),
                   ", ".join(sorted({a['A-LLM-05'][s] for s in SCENARIOS}))))
    checks.append(("Handoff features contract exists", "features.churn_features" in contracts.datasets,
                   handoff["meta"]["feature_contract"]))
    return checks


# ---------------------------------------------------------------- renders
def render_handoff(handoff: dict, r15: dict[str, float], checks) -> str:
    items = pd.DataFrame(handoff["checklist"]).assign(
        blocking=lambda d: d["blocking"].map({True: "**yes**", False: "no"}), status="Open"
    ).rename(columns={"id": "ID", "area": "Area", "item": "Item", "owner": "Owner", "evidence": "Evidence",
                      "blocking": "Blocks go-live", "status": "Status"})
    kpis = pd.DataFrame(handoff["kpis"]).rename(columns=str.title)
    thr = "\n".join(f"- `{k}` " + " and ".join(f"{op} {v}" for op, v in b.items()) for k, b in handoff["go_live_thresholds"].items())
    window = ", ".join(f"{s} = {v:g} months" for s, v in r15.items())
    return f"""# MLOps Handoff — Churn-Risk Model

_Generated by `scripts/build_mlops.py` from `mlops/churn_handoff.yaml`. Do not edit by hand._

**Model:** {handoff['meta']['model']} · **Features:** `{handoff['meta']['feature_contract']}` ·
**Scores land in:** `{handoff['meta']['scores_land_in']}`

**Label:** {' '.join(handoff['label_definition'].split())}

**Training window by regulatory scope (R-15, resolved from the security matrix):** {window}.

## Handoff checklist

Every item marked **yes** must be Done, with its evidence linked, before the model
scores production subscribers.

{md(items)}

## KPIs and SLAs

{md(kpis)}

### Go-live thresholds (enforced by `aurora_mlops.gates.release_gate`)

{thr}

Metrics are computed by `aurora_mlops.metrics.churn_model_kpis`; drift by
`aurora_mlops.drift.feature_drift`. The ROC-AUC floor is a placeholder until the
baseline in H-08 sets it.
"""


def render_ragops(rag: dict, checks) -> str:
    ch = rag["chunking"]
    ev = rag["evaluation"]
    steps = "\n".join(f"{n}. {s}" for n, s in enumerate(ch["steps"], 1))
    why = "\n".join(f"- {r}" for r in ch["rationale"])
    refresh = pd.DataFrame(rag["refresh_cadence"]).rename(columns=str.title)
    suites = pd.DataFrame(ev["suites"]).rename(columns=str.title)
    if "Trials" in suites:
        suites["Trials"] = suites["Trials"].map(lambda v: "—" if pd.isna(v) else f"{v:g}")
    thr = pd.DataFrame(
        [{"Metric": k, "Threshold": " / ".join(f"{op} {v}" for op, v in b.items() if op in ("min", "max")),
          "Claim": b.get("claim", "—")} for k, b in ev["release_thresholds"].items()]
    )
    drift = pd.DataFrame(rag["drift_detection"]["signals"]).rename(columns={"act_at": "Act at"}).rename(columns=str.title)
    rq = pd.DataFrame(rag["retrieval_quality_checks"]).rename(columns={"on_fail": "On fail"}).rename(columns=str.title)
    gs = ev["golden_set"]
    signed, total = signoff_status(ev["signoff"]["rows"])
    online = "\n".join(f"- {o}" for o in ev["online"])
    return f"""# LLMOps / RAGOps Plan — Support-Transcript Corpus

_Generated by `scripts/build_mlops.py` from `mlops/ragops_plan.yaml`. Do not edit by hand._

**Owner:** {rag['meta']['owner']} · **Consumer contract:** {rag['meta']['consumer_contract']} ·
**Dataset:** `{rag['meta']['dataset_contract']}` · **Preconditions:** {', '.join(rag['meta']['preconditions'])}

## 1. Chunking strategy

Implemented in `{ch['implementation']}`. Unit: {ch['unit']}

{steps}

**Why:**

{why}

Token counting: {ch['token_counting']}

## 2. Refresh cadence

{md(refresh)}

## 3. Evaluation method — requires sign-off (RAG-G1)

{' '.join(ev['summary'].split())}

**Golden set:** {gs['size']} questions. {gs['source']} {gs['labels']} Split: {gs['split']}
Refresh: {gs['refresh']}

**Judge:** {ev['judge']['method']} {ev['judge']['calibration']}

### Suites

{md(suites)}

### Release thresholds (enforced by `aurora_mlops.gates.release_gate`)

Retrieval metrics come from `aurora_mlops.metrics.retrieval_report`; `pass^4` from
`aurora_mlops.metrics.pass_hat_k`. A metric that was not measured fails the gate.

{md(thr)}

### Online evaluation

{online}

### Sign-off — {ev['signoff']['gate']}

**Blocks:** {ev['signoff']['blocks']}. **Status:** {'OPEN' if signed == total else f'BLOCKED ({signed}/{total} signed)'}.

{signoff_table(ev['signoff']['rows'])}

## 4. Drift detection

Implemented in `{rag['drift_detection']['implementation']}`.

{md(drift)}

## 5. Retrieval-quality checks

{md(rq)}
"""


def render_cost(a: dict, cfg: dict, i: cost.Inputs, proj: pd.DataFrame, checks) -> str:
    s, month = cfg["meta"]["headline_scenario"], cfg["meta"]["headline_month"]
    subs = proj[(proj["scenario"] == s) & (proj["month"] == month)]["subscribers"].iloc[0]
    items = cost.line_items(i, s, month)
    total = sum(items.values())
    ceiling = a["A-BUD-01"]["base"]

    comp = cfg["components"]
    lines = pd.DataFrame(
        [{"Line item": k.replace("_", " "), "Budget line (A-BUD-02)": comp[k], "USD / month": usd(v)} for k, v in items.items()]
        + [{"Line item": "**Total**", "Budget line (A-BUD-02)": "", "USD / month": f"**{usd(total)}**"}]
    )
    alloc = cost.by_allocation(i, items).reset_index(names="Budget line")
    alloc_tbl = alloc.assign(
        estimate=alloc["estimate"].map(usd), allocation=alloc["allocation"].map(usd),
        share_of_allocation=alloc["share_of_allocation"].map(lambda x: f"{x:.0%}"),
    ).rename(columns={"estimate": "Estimate / month", "allocation": "Allocation / month", "share_of_allocation": "Used"})

    scen_rows = []
    for sc in SCENARIOS:
        it = cost.line_items(i, sc, month)
        al = cost.by_allocation(i, it)
        over = ", ".join(al.index[al["share_of_allocation"] > 1]) or "none"
        sub = proj[(proj["scenario"] == sc) & (proj["month"] == month)]["subscribers"].iloc[0]
        scen_rows.append({"Scenario": sc, "Subscribers (m12)": f"{sub:,.0f}", "Model": a["A-LLM-05"][sc],
                          "USD / month": usd(sum(it.values())), "Annualized": usd(sum(it.values()) * 12),
                          "vs ceiling": f"{sum(it.values()) * 12 / ceiling:.0%}", "Lines over allocation": over})

    model_rows = []
    for model in cfg["price_book"]["models"]:
        it = cost.line_items(i, s, month, model=model)
        model_rows.append({"Assistant model": model, "Per conversation": f"${cost.conversation_cost(i, s, model):.3f}",
                           "Assistant + eval / month": usd(it["assistant_inference"] + it["rag_evaluation"]),
                           "Total / month": usd(sum(it.values())),
                           "Within A-BUD-03 ($/conv)": "yes" if cost.conversation_cost(i, s, model) <= a["A-BUD-03"]["base"] else "no"})

    ing_rows = []
    for pattern in ("micro-batch", "streaming"):
        it = cost.line_items(i, s, month, pattern=pattern)
        ingest = it["micro_batch_loads"] + it["event_collection"] + it.get("streaming_stack", 0.0)
        ing_rows.append({"Ingestion pattern": pattern + (" (ADR-003 decision)" if pattern == cfg["ingestion"]["pattern"] else " (ADR-003 Option A)"),
                         "Ingestion cost / month": usd(ingest), "Total / month": usd(sum(it.values()))})
    delta = sum(cost.line_items(i, s, month, pattern="streaming").values()) - total

    ramp = cost.monthly_series(i, s)
    ramp_tbl = pd.DataFrame({
        "Month": ramp.index,
        "Subscribers": proj[(proj["scenario"] == s) & (proj["month"] > 0)]["subscribers"].map("{:,.0f}".format).to_list(),
        "Assistant LLM": ramp["assistant_inference"].map(usd).to_list(),
        "Total / month": ramp["total"].map(usd).to_list(),
    })
    fy_total = ramp["total"].sum()

    used = ["A-GRW-02", "A-EVT-01", "A-EVT-02", "A-EVT-03", "A-EVT-05", "A-STO-01", "A-STO-02", "A-STO-03",
            "A-TRN-01", "A-TRN-02", "A-TRN-03", "A-TRN-05", "A-BUD-01", "A-BUD-03",
            *sorted(k for k in a if k.startswith(("A-LLM", "A-UC")))]
    stated = pd.DataFrame([{"ID": k, "Assumption": a[k]["name"], "Unit": a[k]["unit"],
                            **{sc: a[k][sc] for sc in SCENARIOS}, "Confidence": a[k]["confidence"]} for k in used])
    per_conv = cost.conversation_cost(i, s)
    signed, n = signoff_status(cfg["signoff"]["rows"])
    pb = cfg["price_book"]
    prices = pd.DataFrame([{"Model": m, **{k.replace('_', ' '): f"${v:.2f}" for k, v in p.items()}} for m, p in pb["models"].items()])
    check_tbl = pd.DataFrame([{"Check": c, "Result": "pass" if ok else "**FAIL**", "Detail": d} for c, ok, d in checks])

    return f"""# Cost-Aware Operating Plan — Subscription Health Data Product

_Generated by `scripts/build_mlops.py` from `mlops/cost_model.yaml`, the assumptions
register and `assumptions/derived/projections.csv`. Do not edit by hand._

**Headline: {usd(total)} per month at {subs:,.0f} subscribers** (month {month}, `{s}` scenario),
{usd(total * 12)} annualized, **{total * 12 / ceiling:.0%} of the {usd(ceiling)} ceiling** (A-BUD-01).
Ingestion is priced as **{cfg['ingestion']['pattern']}** per ADR-003
({cfg['ingestion']['landing_minutes']}-minute landing, {cfg['ingestion']['hourly_incremental_runs_per_day']} hourly
incremental runs per day); the streaming alternative would add **{usd(delta)} per month**.

Every number below is computed from a stated assumption. Unit costs are placeholders
until vendor quotes arrive; LLM prices are list prices. **This estimate needs sign-off
(COST-G1) before budgets or contracts are committed.**

## 1. Monthly estimate at ~250k subscribers

{md(lines)}

### Against the A-BUD-02 allocation

{md(alloc_tbl)}

## 2. Scenarios (month {month})

{md(pd.DataFrame(scen_rows))}

## 3. Decisions the estimate depends on

### Ingestion pattern (ADR-003)

{md(pd.DataFrame(ing_rows))}

### Assistant model (A-LLM-05; chosen at COST-G1, gated by the RAG evaluation)

Per-conversation cost at base usage: ${per_conv:.3f} vs A-BUD-03 target ${a['A-BUD-03']['base']:.2f}.

{md(pd.DataFrame(model_rows))}

The cheaper model is only an option if it passes the same RAG release thresholds
(`docs/ragops_plan.md`); the choice is a business decision at sign-off, not a default.

## 4. Monthly ramp ({s} scenario)

Fiscal-year total: **{usd(fy_total)}**. Fixed lines (orchestrator, tooling, warehouse
schedules) are flat; event, storage and assistant lines follow the subscriber curve.

{md(ramp_tbl)}

## 5. Cost levers, in order

1. **Prompt caching** of the frozen system prompt and tool definitions (A-LLM-04); verify with cache-read token counts in the pilot.
2. **Tight retrieval** (top-k = 5 chunks of ≤ 512 tokens) keeps input tokens near A-LLM-02 base.
3. **Effort / model choice** per the RAG evaluation; only after 1-2, and only where quality holds.
4. **Warehouse auto-suspend and right-sizing**; the nightly build is the largest scheduled compute line.
5. **Usage caps**: if assistant spend exceeds its allocation for two months, ADR-004's supersede rule applies (C-AI-04).

## 6. Stated assumptions

Prices from: {pb['source']}; 5-minute cache writes at {pb['cache_write_multiplier']}x input price.

{md(prices)}

{md(stated)}

## 7. Coupling checks

{md(check_tbl)}

## 8. Sign-off — {cfg['signoff']['gate']}

**Blocks:** {cfg['signoff']['blocks']}. **Status:** {'OPEN' if signed == n else f'BLOCKED ({signed}/{n} signed)'}.

{signoff_table(cfg['signoff']['rows'])}
"""


def main() -> int:
    meta, a = load_assumptions()
    cfg, rag, handoff = _yaml("cost_model.yaml"), _yaml("ragops_plan.yaml"), _yaml("churn_handoff.yaml")
    proj = pd.read_csv(ROOT / "assumptions" / "derived" / "projections.csv")
    claims = pd.read_csv(ROOT / "evidence" / "own_testing_claims.csv", dtype=str)
    security = load_matrix()
    contracts = load_contracts()

    checks = coupling_checks(a, cfg, rag, handoff, claims, security, contracts)
    r15 = {sc: resolve_retention(security, a, sc, regimes_in_scope(security, a, sc))["R-15"]["months"] for sc in SCENARIOS}
    i = cost.Inputs(a, proj, cfg)

    outputs = {
        DOCS / "mlops_churn_handoff.md": render_handoff(handoff, r15, checks),
        DOCS / "ragops_plan.md": render_ragops(rag, checks),
        DOCS / "cost_operating_plan.md": render_cost(a, cfg, i, proj, checks),
    }
    for path, text in outputs.items():
        path.write_text(text, encoding="utf-8")
        print(f"Wrote {path.relative_to(ROOT).as_posix()}")

    s, m = cfg["meta"]["headline_scenario"], cfg["meta"]["headline_month"]
    print(f"Month-{m} {s} estimate: ${sum(cost.line_items(i, s, m).values()):,.0f}/month")
    for name, rows in (("COST-G1 cost estimate", cfg["signoff"]["rows"]), ("RAG-G1 evaluation method", rag["evaluation"]["signoff"]["rows"])):
        signed, n = signoff_status(rows)
        print(f"{name}: {'OPEN' if signed == n else f'BLOCKED ({signed}/{n} signed)'}")
    failed = [c for c in checks if not c[1]]
    for c, _, d in failed:
        print(f"  FAIL {c}: {d}", file=sys.stderr)
    print(f"Coupling checks: {len(checks) - len(failed)}/{len(checks)} passed")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
